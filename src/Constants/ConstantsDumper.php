namespace Silarhi\AppJsBundle\Constants;

use InvalidArgumentException;
use ReflectionClass;
use ReflectionClassConstant;
use Silarhi\AppJsBundle\Writer\Format;
use Silarhi\AppJsBundle\Writer\Literal;

use function sprintf;
use function strlen;

/**
 * One module per class (TypeScript or JavaScript: the same code): an export per public constant, in their order, the
 * arrays frozen.
 *
 *     // Generated by app-js:dump-constants from App\Model\Upload, do not edit
 *     export const MAX_SIZE = 2000000
 *     export const MIME_TYPES = Object.freeze(['image/jpeg', 'image/png'])
 *
 * A constant holding an enum case gives its value (its name for a unit enum). Any other object is refused: it has no
 * JavaScript literal.
 *
 * @internal
 */
final readonly class ConstantsDumper
{
    /**
     * @param array<string, class-string> $classes the classes marked #[ConstantsToJs], by module name
     */
    public function __construct(
        private array $classes,
        private Format $format = Format::TypeScript,
    ) {
    }

    /** The extension of the dumped files: ts or js. */
    public function getExtension(): string
    {
        return $this->format->value;
    }

    /**
     * @return array<string, string> the content of each file, by its path relative to the output directory
     */
    public function getFiles(): array
    {
        $files = [];
        foreach ($this->classes as $name => $class) {
            $constants = array_filter(
                (new ReflectionClass($class))->getReflectionConstants(ReflectionClassConstant::IS_PUBLIC),
                // An enum's cases are constants too: app-js:dump-enums dumps them
                static fn (ReflectionClassConstant $constant): bool => !$constant->isEnumCase(),
            );
            if ([] === $constants) {
                continue;
            }

            $exports = array_map(
                fn (ReflectionClassConstant $constant): string => $this->export($class, $constant),
                array_values($constants),
            );
            $files[$name . '.' . $this->getExtension()] = sprintf("// Generated by app-js:dump-constants from %s, do not edit\n%s\n", $class, implode("\n", $exports));
        }

        return $files;
    }

    /**
     * @param class-string $class
     */
    private function export(string $class, ReflectionClassConstant $constant): string
    {
        $prefix = sprintf('export const %s = ', $constant->getName());

        try {
            return $prefix . Literal::render($constant->getValue(), strlen($prefix));
        } catch (InvalidArgumentException $exception) {
            throw new InvalidArgumentException(sprintf('The constant %s::%s cannot be dumped: %s', $class, $constant->getName(), $exception->getMessage()), $exception->getCode(), previous: $exception);
        }
    }
}
