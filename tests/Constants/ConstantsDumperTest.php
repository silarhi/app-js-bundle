namespace Silarhi\AppJsBundle\Tests\Constants;

use PHPUnit\Framework\Attributes\RequiresPhp;
use PHPUnit\Framework\TestCase;
use Silarhi\AppJsBundle\Constants\ConstantsDumper;
use Silarhi\AppJsBundle\Tests\Fixtures\Constants\Format as FormatEnum;
use Silarhi\AppJsBundle\Tests\Fixtures\Constants\Internals;
use Silarhi\AppJsBundle\Tests\Fixtures\Constants\SearchLimits;
use Silarhi\AppJsBundle\Tests\Fixtures\Constants\Upload;
use Silarhi\AppJsBundle\Tests\Fixtures\TypedConstants\Typed;
use Silarhi\AppJsBundle\Writer\Format;

final class ConstantsDumperTest extends TestCase
{
    public function testDumpsAModulePerClassWithPublicConstants(): void
    {
        self::assertSame(['Format.ts', 'Limits.ts', 'Upload.ts'], array_keys($this->createDumper()->getFiles()));
    }

    public function testRendersEveryPublicConstantAsBiomeFormatsIt(): void
    {
        self::assertSame(<<<'TS'
            // Generated by app-js:dump-constants from Silarhi\AppJsBundle\Tests\Fixtures\Constants\Upload, do not edit
            export const MAX_SIZE = 2000000
            export const RATIO = 1.7777777777777777
            export const LABEL = "it's"
            export const ENABLED = true
            export const NOTHING = null
            export const MIME_TYPES = Object.freeze(['image/jpeg', 'image/png'])
            export const SIZES = Object.freeze({
                '2:1': Object.freeze([1200, 600]),
                tall: Object.freeze([900, 1200]),
            })
            export const EMPTY = Object.freeze([])
            export const STATUS = 'draft'
            export const KIND = 'Text'
            export const LONG = Object.freeze([
                'jpeg-image-format',
                'png-image-format',
                'gif-image-format',
                'webp-image-format',
                'avif-image-format',
            ])

            TS, $this->createDumper()->getFiles()['Upload.ts']);
    }

    public function testDumpsTheConstantsOfAnEnumButNotItsCases(): void
    {
        self::assertSame(
            "// Generated by app-js:dump-constants from Silarhi\\AppJsBundle\\Tests\\Fixtures\\Constants\\Format, do not edit\nexport const MAX_PAGES = 24\n",
            $this->createDumper()->getFiles()['Format.ts'],
        );
    }

    #[RequiresPhp('>= 8.3.0')]
    public function testDumpsTypedConstantsByTheirValue(): void
    {
        self::assertSame(<<<'TS'
            // Generated by app-js:dump-constants from Silarhi\AppJsBundle\Tests\Fixtures\TypedConstants\Typed, do not edit
            export const MAX_SIZE = 2000000
            export const NOTHING = null
            export const RATIO = 1.7777777777777777
            export const SIZES = Object.freeze({
                tall: Object.freeze([900, 1200]),
            })
            export const STATUS = 'draft'

            TS, (new ConstantsDumper(['Typed' => Typed::class]))->getFiles()['Typed.ts']);
    }

    public function testDumpsTheSameCodeAsJavaScript(): void
    {
        $javaScript = $this->createDumper(Format::JavaScript)->getFiles();

        self::assertSame(['Format.js', 'Limits.js', 'Upload.js'], array_keys($javaScript));
        self::assertSame($this->createDumper()->getFiles()['Upload.ts'], $javaScript['Upload.js']);
    }

    public function testSkipsTheClassesWithoutPublicConstant(): void
    {
        self::assertSame([], (new ConstantsDumper(['Internals' => Internals::class]))->getFiles());
    }

    private function createDumper(Format $format = Format::TypeScript): ConstantsDumper
    {
        return new ConstantsDumper(['Format' => FormatEnum::class, 'Limits' => SearchLimits::class, 'Upload' => Upload::class], $format);
    }
}
