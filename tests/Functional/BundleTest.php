namespace Silarhi\AppJsBundle\Tests\Functional;

use function dirname;

use Silarhi\AppJsBundle\Tests\Fixtures\TestKernel;
use Symfony\Bundle\FrameworkBundle\Console\Application;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Output\OutputInterface;
use Symfony\Component\Console\Tester\CommandTester;
use Symfony\Component\Filesystem\Filesystem;
use Twig\Environment;

final class BundleTest extends KernelTestCase
{
    protected static function getKernelClass(): string
    {
        return TestKernel::class;
    }

    protected function setUp(): void
    {
        (new Filesystem())->remove([dirname(__DIR__, 2) . '/var/cache/test/app_js', dirname(__DIR__, 2) . '/var/cache/js/app_js']);
    }

    public function testDumpsTheFormShapes(): void
    {
        $tester = $this->executeCommand('app-js:dump-forms');

        $tester->assertCommandIsSuccessful();
        self::assertStringContainsString('Dumped 3 form shape(s), 3 file(s) changed.', $tester->getDisplay());

        $directory = self::$kernel?->getCacheDir() . '/app_js/forms';
        self::assertSame(<<<'TS'
            // Generated by app-js:dump-forms from Silarhi\AppJsBundle\Tests\Fixtures\Form\UserType, do not edit
            import type { AnyShape, FormCollection, FormField } from '@silarhi/app-js/form'

            export interface UserForm {
                name: FormField
                size: FormField
                tags: FormField
                address: {
                    street: FormField
                    city: FormField
                }
                phones: FormCollection<{
                    number: FormField
                }>
                notes: FormCollection<FormField>
                emails: FormCollection<AnyShape>
                'start-date': FormField
                siren?: FormField
            }

            TS, file_get_contents($directory . '/UserForm.ts'));

        self::assertStringContainsString("export interface Lease {\n    reference: FormField\n    inventory?: FormField\n}\n", (string) file_get_contents($directory . '/Lease.ts'));
        self::assertFileExists($directory . '/ContactForm.ts');
    }

    public function testDumpsJavaScriptModulesAndDeclarations(): void
    {
        $this->executeCommand('app-js:dump-enums', [], 'js')->assertCommandIsSuccessful();
        $this->executeCommand('app-js:dump-forms', [], 'js')->assertCommandIsSuccessful();

        $cacheDir = self::$kernel?->getCacheDir();
        self::assertFileExists($cacheDir . '/app_js/enums/Status.js');
        self::assertFileExists($cacheDir . '/app_js/forms/UserForm.d.ts');
        self::assertFileDoesNotExist($cacheDir . '/app_js/forms/UserForm.ts');
        self::assertSame(Command::SUCCESS, $this->executeCommand('app-js:dump-forms', ['--check' => true], 'js')->getStatusCode());
    }

    public function testWarnsAboutListenersWithoutDataVariant(): void
    {
        $display = (string) preg_replace('/\s+/', ' ', $this->executeCommand('app-js:dump-forms')->getDisplay());

        self::assertStringContainsString('ContactType adds PRE_SET_DATA listeners ("(root)" from Silarhi\\AppJsBundle\\Tests\\Fixtures\\Form\\ContactType)', $display);
        self::assertStringNotContainsString('LeaseType adds', $display);
    }

    public function testStrictFailsOnTheWarnings(): void
    {
        $tester = $this->executeCommand('app-js:dump-forms', ['--strict' => true]);

        self::assertSame(Command::FAILURE, $tester->getStatusCode());
        self::assertStringContainsString('1 form(s) may miss fields (--strict).', $tester->getDisplay());
    }

    public function testListsTheChangedFilesWhenVerbose(): void
    {
        $enums = $this->executeCommand('app-js:dump-enums', [], verbosity: OutputInterface::VERBOSITY_VERBOSE)->getDisplay();
        $forms = $this->executeCommand('app-js:dump-forms', [], verbosity: OutputInterface::VERBOSITY_VERBOSE)->getDisplay();

        self::assertStringContainsString('* Status.ts', $enums);
        self::assertStringContainsString('* UserForm.ts', $forms);
    }

    public function testCheckFailsOnOutOfDateFormShapes(): void
    {
        $tester = $this->executeCommand('app-js:dump-forms', ['--check' => true]);

        self::assertSame(Command::FAILURE, $tester->getStatusCode());
        self::assertStringContainsString('* UserForm.ts', $tester->getDisplay());
        self::assertStringContainsString('3 form file(s) out of date', (string) preg_replace('/\s+/', ' ', $tester->getDisplay()));
    }

    public function testCheckFailsUntilTheFilesAreDumped(): void
    {
        self::assertSame(Command::FAILURE, $this->executeCommand('app-js:dump-enums', ['--check' => true])->getStatusCode());

        $this->executeCommand('app-js:dump-enums')->assertCommandIsSuccessful();
        $tester = $this->executeCommand('app-js:dump-enums', ['--check' => true]);

        $tester->assertCommandIsSuccessful();
        self::assertStringContainsString('3 enum file(s) up to date.', $tester->getDisplay());
    }

    public function testRendersLoadPage(): void
    {
        self::bootKernel();
        $twig = self::getContainer()->get('twig');
        self::assertInstanceOf(Environment::class, $twig);

        self::assertSame(
            '<div data-page="[&quot;party&quot;]" data-page-params="{&quot;id&quot;:3,&quot;name&quot;:&quot;A &amp; \\&quot;B\\&quot;&quot;}"></div>' . "\n"
            . '<div data-page="[&quot;a&quot;,&quot;b&quot;]" data-page-params="{}"></div>' . "\n",
            $twig->render('page.html.twig'),
        );
    }

    /**
     * @param array<string, mixed> $input
     */
    private function executeCommand(string $name, array $input = [], string $environment = 'test', int $verbosity = OutputInterface::VERBOSITY_NORMAL): CommandTester
    {
        $tester = new CommandTester((new Application(self::bootKernel(['environment' => $environment])))->find($name));
        $tester->execute($input, ['verbosity' => $verbosity]);

        return $tester;
    }
}
