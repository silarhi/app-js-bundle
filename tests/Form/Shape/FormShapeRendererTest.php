namespace Silarhi\AppJsBundle\Tests\Form\Shape;

use PHPUnit\Framework\TestCase;
use Silarhi\AppJsBundle\Form\Shape\FormShapeRenderer;
use Silarhi\AppJsBundle\Form\Shape\ShapeNode;

final class FormShapeRendererTest extends TestCase
{
    public function testImportsOnlyTheTypesItUses(): void
    {
        $ts = (new FormShapeRenderer())->render('NameForm', 'App\\Form\\NameType', ShapeNode::form(['name' => ShapeNode::field()]));

        self::assertSame(<<<'TS'
            // Generated by app-js:dump-forms from App\Form\NameType, do not edit
            import type { FormField } from '@silarhi/app-js/form'

            export interface NameForm {
                name: FormField
            }

            TS, $ts);
    }

    public function testRendersAFormWithoutFieldsAsAType(): void
    {
        $ts = (new FormShapeRenderer())->render('EmptyForm', 'App\\Form\\EmptyType', ShapeNode::form([]));

        self::assertSame("// Generated by app-js:dump-forms from App\\Form\\EmptyType, do not edit\n\nexport type EmptyForm = Record<string, never>\n", $ts);
    }

    public function testRendersAnUnknownItemAsAnyShape(): void
    {
        $ts = (new FormShapeRenderer())->render('TagsForm', 'App\\Form\\TagsType', ShapeNode::form(['tags' => ShapeNode::collection(null)]));

        self::assertStringContainsString("import type { AnyShape, FormCollection } from '@silarhi/app-js/form'", $ts);
        self::assertStringContainsString('    tags: FormCollection<AnyShape>', $ts);
    }
}
