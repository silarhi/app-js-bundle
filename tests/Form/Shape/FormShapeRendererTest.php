namespace Silarhi\AppJsBundle\Tests\Form\Shape;

use PHPUnit\Framework\TestCase;
use Silarhi\AppJsBundle\Form\Shape\FormShapeRenderer;
use Silarhi\AppJsBundle\Form\Shape\ShapeNode;
use Silarhi\AppJsBundle\Tests\Fixtures\Form\AddressType;
use Silarhi\AppJsBundle\Tests\Fixtures\Form\UserType;

final class FormShapeRendererTest extends TestCase
{
    public function testImportsOnlyTheTypesItUses(): void
    {
        $ts = (new FormShapeRenderer())->render('NameForm', 'App\\Form\\NameType', ShapeNode::form(['name' => ShapeNode::field()]));

        self::assertSame(<<<'TS'
            // Generated by app-js:dump-forms from App\Form\NameType, do not edit
            import type { FormField } from '@silarhi/app-js/form'

            export interface NameForm {
                name: FormField
            }

            TS, $ts);
    }

    public function testNamesTheElementOfAField(): void
    {
        $ts = (new FormShapeRenderer())->render('KindForm', 'App\\Form\\KindType', ShapeNode::form(['kind' => ShapeNode::field('HTMLSelectElement'), 'other' => ShapeNode::field()]));

        self::assertStringContainsString("    kind: FormField<HTMLSelectElement>\n    other: FormField\n", $ts);
    }

    public function testReferencesTheDumpedFormsOfTheSameShape(): void
    {
        $category = ShapeNode::form([
            'name' => ShapeNode::field(),
            'parent' => ShapeNode::form(['name' => ShapeNode::field()], AddressType::class),
            'children' => ShapeNode::collection(ShapeNode::form([], UserType::class)),
        ], UserType::class);
        $references = [
            UserType::class => ['name' => 'UserForm', 'shape' => ShapeNode::form([])],
            AddressType::class => ['name' => 'AddressForm', 'shape' => ShapeNode::form(['name' => ShapeNode::field(), 'slug' => ShapeNode::field()])],
        ];

        self::assertSame(<<<'TS'
            // Generated by app-js:dump-forms from Silarhi\AppJsBundle\Tests\Fixtures\Form\UserType, do not edit
            import type { FormCollection, FormField } from '@silarhi/app-js/form'

            export interface UserForm {
                name: FormField
                parent: {
                    name: FormField
                }
                children: FormCollection<UserForm>
            }

            TS, (new FormShapeRenderer())->render('UserForm', UserType::class, $category, $references));
    }

    public function testRendersAFormWithoutFieldsAsAType(): void
    {
        $ts = (new FormShapeRenderer())->render('EmptyForm', 'App\\Form\\EmptyType', ShapeNode::form([]));

        self::assertSame("// Generated by app-js:dump-forms from App\\Form\\EmptyType, do not edit\n\nexport type EmptyForm = Record<string, never>\n", $ts);
    }

    public function testRendersAnUnknownItemAsAnyShape(): void
    {
        $ts = (new FormShapeRenderer())->render('TagsForm', 'App\\Form\\TagsType', ShapeNode::form(['tags' => ShapeNode::collection(null)]));

        self::assertStringContainsString("import type { AnyShape, FormCollection } from '@silarhi/app-js/form'", $ts);
        self::assertStringContainsString('    tags: FormCollection<AnyShape>', $ts);
    }
}
